export function getSuggestionsByPreference(pref: string): MealSuggestion[] {
  if (pref === 'custom') return mealSuggestions;
  return mealSuggestions.filter((m) => m.preference.includes(pref as never));
}

export function getSuggestionsByType(pref: string, type: string): MealSuggestion[] {
  return getSuggestionsByPreference(pref).filter((m) => m.type === type);
}
